import PizZip from 'pizzip'
import { applyStyleSetToPart } from './applyStyleSet'
import type { StyleSetSettings } from './schema'

/**
 * Apply a style set across every part of an existing .docx.
 *
 * The generator does this one part at a time while rendering a template
 * (`lib/estateGenerator/node/templateRenderer.ts`). The Word add-in needs the
 * same sweep over a document that already exists, so the loop lives here and
 * both callers get the same answer.
 *
 * That equivalence is the point. Reimplementing the firm's formatting rules in
 * Office.js would create a second engine that drifts from the one producing
 * generated documents — a document formatted in Word and the same document
 * generated by Cornerstone would slowly stop matching. Round-tripping the bytes
 * through this one applier makes drift impossible.
 */
export function applyStyleSetToDocxBuffer(
  bytes: Buffer,
  settings: StyleSetSettings,
): { buffer: Buffer; changedParts: string[] } {
  const zip = new PizZip(bytes)
  const changedParts: string[] = []

  for (const fileName of Object.keys(zip.files)) {
    const file = zip.files[fileName]
    // Only the WordprocessingML parts carry formatting. Media, relationships,
    // and the content-type map pass through untouched.
    if (file.dir || !fileName.startsWith('word/') || !fileName.endsWith('.xml')) continue

    const original = file.asText()
    const styled = applyStyleSetToPart(fileName, original, settings)
    if (styled !== original) {
      zip.file(fileName, styled)
      changedParts.push(fileName)
    }
  }

  return {
    buffer: Buffer.from(zip.generate({ type: 'uint8array', compression: 'DEFLATE' })),
    changedParts,
  }
}
