export const SHARED_FIELD_REGISTRY = defs

export function getSharedField(id: SharedFieldId): SharedFieldDef {
  return defs[id]
}

export function sharedFieldOptions(
  id: SharedFieldId,
  ctx: Parameters<NonNullable<SharedFieldDef['optionsFor']>>[0] = {},
): readonly { value: string; label: string }[] {
  const def = defs[id]
  if (def.optionsFor) return def.optionsFor(ctx)
  return def.options ?? []
}

