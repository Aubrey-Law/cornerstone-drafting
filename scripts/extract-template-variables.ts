/**
 * Regenerate the template-variable catalog:
 *   npx tsx scripts/extract-template-variables.ts
 *
 * Scans every DOCX in tools/aubreylaw-docgeneration/templates/, extracts the
 * Nunjucks merge fields, control-flow paths, and include_clause ids, and
 * writes schemas/template-variables.generated.json. Unknown variable roots
 * (nothing in the generator populates them) and unknown clause ids are
 * reported and make the run exit non-zero — the same check runs in CI via
 * tests/template-variable-catalog.test.ts.
 */
import fs from 'node:fs'
import path from 'node:path'
import { BASELINE_UNKNOWN_ROOTS, buildTemplateVariableCatalog } from '@/lib/estateGenerator/templateVariables'
import { resolveNodeEstateGeneratorRoot } from '@/lib/estateGenerator/node/config'

const root = resolveNodeEstateGeneratorRoot()
const catalog = buildTemplateVariableCatalog(root)

const outputPath = path.join(root, 'schemas', 'template-variables.generated.json')
const output = {
  note: 'Generated by scripts/extract-template-variables.ts — do not edit by hand.',
  templates: Object.fromEntries(
    catalog.map(entry => [entry.template, {
      variables: entry.variables,
      clauses: entry.clauses,
      localVariables: entry.localVariables,
    }]),
  ),
}
fs.writeFileSync(outputPath, `${JSON.stringify(output, null, 2)}\n`)
console.log(`Wrote ${path.relative(process.cwd(), outputPath)} (${catalog.length} templates)`)

let failed = false
for (const entry of catalog) {
  const baselined = BASELINE_UNKNOWN_ROOTS[entry.template] ?? []
  const newUnknownRoots = entry.unknownRoots.filter(root => !baselined.includes(root))
  const grandfathered = entry.unknownRoots.filter(root => baselined.includes(root))
  if (grandfathered.length > 0) {
    console.warn(`⚠ ${entry.template}: baselined dangling roots — ${grandfathered.join(', ')}`)
  }
  if (newUnknownRoots.length > 0) {
    failed = true
    console.error(`✗ ${entry.template}: unknown variable roots — ${newUnknownRoots.join(', ')}`)
  }
  if (entry.unknownClauses.length > 0) {
    failed = true
    console.error(`✗ ${entry.template}: unknown clause ids — ${entry.unknownClauses.join(', ')}`)
  }
}
if (failed) {
  console.error('\nA template references data nothing populates. Add the field to the pipeline, fix the template, or (if intentional) baseline it in tests/template-variable-catalog.test.ts.')
  process.exit(1)
}
console.log('✓ every template variable root and clause id is known')
