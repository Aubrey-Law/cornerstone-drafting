/**
 * What surrounds the agenda. The two meetings differ most here: a PMPS usually
 * happens on a lead, before there is a design sheet to open, so its notes reach
 * the sheet only once the matter is hired.
 */
const CHECKLIST_FRAME: Record<MeetingSpec['key'], { intro: string[]; before: string[]; after: string[] }> = {
  pmps: {
    intro: [
      'The order to run a Peace of Mind Planning Session, and what each section has to come away',
      'with. It gathers the facts the Estate Plan Proposal and the Massachusetts estate-tax',
      'worksheet need, and the first version of the plan. Provisions wait for the design meeting.',
    ],
    before: [
      '- [ ] Read the intake questionnaire and the lead\'s notes; do not re-ask what they answer.',
      '- [ ] Run **PMPS Proposal Preflight** in the Assistant on the lead so the gaps are known',
      '      before the client arrives.',
      '- [ ] Start Granola with the PMPS template, or print the PMPS worksheet.',
    ],
    after: [
      '- [ ] Run the **PMPS recipe** in Granola. Attach its recap to the lead with',
      '      **Add meeting notes**.',
      '- [ ] Work the recipe\'s **Missing information** list into the follow-up email — every',
      '      asset line still without a number, and every policy without an owner.',
      '- [ ] Once the matter is hired, open `/admin/drafting/<matterId>` and paste the recap',
      '      above **Missing information** into **Complete sheet → Paste notes**, or upload the',
      '      worksheet through **Complete sheet → Word document**.',
      '- [ ] Review and accept, then use **Create follow-up task** in the same dialog to turn what',
      '      the sheet still lacks into a checklist task on the matter.',
      '- [ ] Billing (legal plan, fee quoted) has no design-sheet field. Record it on the matter;',
      '      the import carries it only as drafting notes.',
    ],
  },
  'design-meeting': {
    intro: [
      'The order to work through a design meeting, and what each section has to come away with.',
      'Pair it with `design-meeting-worksheet.docx`, which carries the same sections in the same',
      'order and is what gets uploaded afterwards.',
    ],
    before: [
      '- [ ] Open the matter at `/admin/drafting/<matterId>` so the design sheet is seeded.',
      '- [ ] Note the number on the **Complete sheet** button — that is what still blocks drafting.',
      '- [ ] Run **Complete sheet → Fill what is missing** and accept what intake already supports,',
      '      so the meeting is spent on decisions rather than on data entry.',
      '- [ ] Print the worksheet, or open it alongside the sheet.',
    ],
    after: [
      '- [ ] Upload the worksheet: **Complete sheet → Word document → Read document**.',
      '      From Granola instead: run the design-meeting recipe and paste its recap into',
      '      **Complete sheet → Paste notes**.',
      '- [ ] Review the proposed rows. Anything in the **rejected** panel is a value the field',
      '      cannot hold — set it on the sheet directly rather than rewording the worksheet.',
      '- [ ] Check the **People** group before accepting: a row badged *Creates a new contact*',
      '      will mint a contact record, so confirm it is not someone already on the matter under',
      '      a different spelling.',
      '- [ ] Accept, then confirm the **Complete sheet** count dropped.',
      '- [ ] Use **Create follow-up task** to put whatever is still open on the matter as a',
      '      checklist task, split into client questions and attorney decisions.',
      '- [ ] Anything left undecided stays a client question — it belongs in Concerns, not in a',
      '      value nobody chose.',
    ],
  },
}

function buildChecklist(spec: MeetingSpec): string {
  const frame = CHECKLIST_FRAME[spec.key]
  const lines: string[] = [
    `# ${spec.title} — Checklist`,
    '',
    GENERATED_NOTE,
    '',
    ...frame.intro,
    '',
    '## Before the meeting',
    '',
    ...frame.before,
    '',
    '## During the meeting',
    '',
  ]

  for (const [index, section] of spec.sections.entries()) {
    lines.push(`### ${index + 1}. ${section.title}`, '', section.intro, '')
    for (const field of section.fields) {
      const meta = getDesignSheetImportFieldMeta(field)
      if (!meta) throw new Error(`Unknown design-sheet field in the meeting spec: ${field}`)
      const options = meta.options ? ` — ${meta.options.join(' / ')}` : ''
      lines.push(`- [ ] ${meta.label}${options}`)
    }
    for (const prompt of section.prompts ?? []) lines.push(`- [ ] ${prompt}`)
    lines.push('')
  }

  lines.push('## After the meeting', '', ...frame.after, '')

  return lines.join('\n')
}

// --- granola template --------------------------------------------------------

/** The section headings and labelled lines both the template and the recipe use. */
function templateBody(spec: MeetingSpec): string[] {
  const lines: string[] = []
  for (const section of spec.sections) {
    lines.push(`### ${section.title}`, '', section.intro, '')
    for (const field of section.fields) lines.push(`- ${noteLabel(field)}:`)
    for (const prompt of section.prompts ?? []) lines.push(`- ${prompt}:`)
    lines.push('')
  }
  return lines
}

function buildGranolaTemplate(spec: MeetingSpec): string {
  const paths = meetingArtifactPaths(spec)
  const lines: string[] = [
    `# Granola Template — ${spec.title}`,
    '',
    GENERATED_NOTE,
    '',
    'Paste the sections below into Granola\'s template editor. They mirror the worksheet, so a',
    'note taken against this template already carries the labels the design sheet reads.',
    `After the meeting, run the recipe in \`${path.basename(paths.recipe)}\` to tidy the note and`,
    'list what is still missing.',
    '',
    'Two ways the note reaches the sheet:',
    '',
    '1. Paste it into **Complete sheet → Paste notes**.',
    '2. Attach it to the matter with **Add meeting notes**; **Fill what is missing** reads recent',
    '   matter notes on its own.',
    '',
    '---',
    '',
    '## Template',
    '',
    '**Instructions for the notetaker**',
    '',
    'Capture only what was actually said. Where a decision was not reached, write',
    '"not decided" rather than inferring one — an unanswered question is a useful output, and a',
    'plausible guess becomes a drafted document. Use the client\'s own words for names.',
    '',
    ...templateBody(spec),
  ]

  return lines.join('\n')
}

// --- granola recipe ----------------------------------------------------------

/**
 * A Granola recipe: the prompt run over a finished note.
 *
 * It does two jobs the template cannot. It rewrites a note that drifted from the
 * template back into the exact labels and option tokens the importer accepts,
 * and it lists every label still empty — which is the meeting's follow-up list.
 * The recap ends at "Missing information" on purpose: everything above that
 * heading is meant for **Paste notes**, and the lists below it are not facts.
 */
function buildGranolaRecipe(spec: MeetingSpec): string {
  const paths = meetingArtifactPaths(spec)
  const recipeName = spec.key === 'pmps' ? 'PMPS → design sheet' : 'Design meeting → design sheet'
  const lines: string[] = [
    `# Granola Recipe — ${spec.title}`,
    '',
    GENERATED_NOTE,
    '',
    `Create a recipe in Granola named **${recipeName}** and paste everything under **Recipe prompt**`,
    `into it. Run it on a note taken with \`${path.basename(paths.granola)}\` (or on any note of this`,
    'meeting — it works from the transcript too).',
    '',
    'What comes back:',
    '',
    '1. **Design sheet recap** — every label the template carries, answered or marked',
    '   "not decided". Paste this part, and only this part, into **Complete sheet → Paste notes**.',
    '2. **Missing information** — every label still blank, split into what to ask the client and',
    '   what the attorney has to decide.',
    '3. **Follow-up tasks** — the missing information as a checklist, ready for the follow-up email',
    '   or the matter\'s task list.',
    '',
    '---',
    '',
    '## Recipe prompt',
    '',
    `You are preparing the record of an Aubrey Law ${spec.title} (Massachusetts estate planning)`,
    'for import into the firm\'s design sheet. Work only from this meeting\'s notes and transcript.',
    '',
    'Rules:',
    '',
    '- Never invent or infer a fact, a name, a value, or a decision. If it was not said, the answer',
    '  is "not decided".',
    '- Keep every label exactly as written below, one label per line, answer after the colon.',
    '- Where a label lists choices in brackets, answer with one of those tokens exactly as printed,',
    '  or "not decided". Do not paraphrase a choice.',
    '- Write dates as YYYY-MM-DD and money as a plain number of dollars (e.g. 450000).',
    '- Full legal names for every person. Add the relationship in brackets when it is not obvious.',
    '- Where a client gave two different figures for the same thing, write both and say which was',
    '  said last. Do not pick one.',
    '- For assets, one line per asset under the asset prompts: description, institution, value,',
    '  current owner, beneficiary.',
    '',
    'Output exactly three sections, in this order.',
    '',
    '## Design sheet recap',
    '',
    ...templateBody(spec).map(line => (line.startsWith('### ') ? line.replace('### ', '#### ') : line)),
    '## Missing information',
    '',
    'List every label above answered "not decided" or left blank, under two headings:',
    '',
    '- **Ask the client** — facts only the client can supply (names, dates, values, owners,',
    '  documents to send).',
    '- **Attorney to decide** — plan choices and provisions the attorney must settle or recommend.',
    '',
    'Also list here anything said in the meeting that contradicts itself, with both versions.',
    '',
    '## Follow-up tasks',
    '',
    'A checklist, one task per line, in the form:',
    '',
    '- [ ] <what to do> — <who: client / attorney / staff> — <by when, if one was agreed>',
    '',
    'Include every item from Missing information, plus any next step agreed in the meeting',
    '(documents to send, the next meeting to book, a fee or engagement letter to send).',
    '',
  ]

  return lines.join('\n')
}

// --- entry points ------------------------------------------------------------

export interface DesignMeetingArtifacts {
  /** Worksheet .docx files keyed by repo-relative path. */
  worksheets: Record<string, Buffer>
  /** Markdown files keyed by repo-relative path. */
  markdown: Record<string, string>
}

export async function buildDesignMeetingArtifacts(): Promise<DesignMeetingArtifacts> {
  const worksheets: Record<string, Buffer> = {}
  const markdown: Record<string, string> = {}

  for (const spec of MEETING_SPECS) {
    const paths = meetingArtifactPaths(spec)
    worksheets[paths.worksheet] = normalizeDocx(await Packer.toBuffer(buildWorksheetDocument(spec)))
    markdown[paths.checklist] = buildChecklist(spec)
    markdown[paths.granola] = buildGranolaTemplate(spec)
    markdown[paths.recipe] = buildGranolaRecipe(spec)
  }

  return { worksheets, markdown }
}

async function main() {
  const repoRoot = process.cwd()
  const { worksheets, markdown } = await buildDesignMeetingArtifacts()

  const files: Array<[string, Buffer | string]> = [...Object.entries(worksheets), ...Object.entries(markdown)]
  for (const [relative, content] of files) {
    const out = path.join(repoRoot, relative)
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, content)
    console.log(`Wrote ${relative}`)
  }
}

if (process.argv[1] && process.argv[1].includes('generate-design-meeting-forms')) {
  void main()
}
