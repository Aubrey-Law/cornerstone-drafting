/**
 * Build the design-meeting capture artifacts from the design-sheet registries.
 *
 * Run with `npm run design:forms`. Three outputs from one spec:
 *
 *   worksheet (.docx)  filled in during the meeting, uploaded afterwards through
 *                      Complete sheet → Word document
 *   checklist (.md)    the agenda the attorney runs the meeting from
 *   granola (.md)      pasted into Granola's template editor so the recorded
 *                      note comes out in the shape the same extractor reads
 *
 * Labels and option lists are read from `getDesignSheetImportFieldMeta` rather
 * than written by hand, so the worksheet can only ever print tokens the import
 * validator accepts. tests/design-meeting-forms-freshness.test.ts fails when
 * that stops being true.
 */
import fs from 'node:fs'
import path from 'node:path'
import { AlignmentType, Document, HeadingLevel, Packer, Paragraph, TextRun } from 'docx'
import PizZip from 'pizzip'
import {
  DESIGN_MEETING_SECTIONS,
  type DesignMeetingSection,
} from '../lib/designMeeting/formSpec'
import { getDesignSheetImportFieldMeta } from '../lib/designSheetImport/shared'

// Deliberately NOT in tools/aubreylaw-docgeneration/templates/. That directory
// means "Nunjucks templates the estate generator renders", and both the
// doc-template skill references and the template-variable catalog enumerate it.
// This worksheet carries no merge fields — it is a blank form to write on — so
// filing it there would list it as a renderable template with zero variables.
export const WORKSHEET_PATH = 'docs/design-meeting/design-meeting-worksheet.docx'
export const CHECKLIST_PATH = 'docs/design-meeting/checklist.md'
export const GRANOLA_PATH = 'docs/design-meeting/granola-template.md'

const GENERATED_NOTE = '<!-- Generated by `npm run design:forms`. Edit lib/designMeeting/formSpec.ts, not this file. -->'

const deterministicCoreDocxTimestamp = '2000-01-01T00:00:00.000Z'
const deterministicZipEntryDate = new Date(2000, 0, 1, 0, 0, 0)

const ANSWER_RULE = '_______________________________________________'

/**
 * The line a field gets on the worksheet.
 *
 * Choice fields print their allowed values because the extractor validates
 * against exactly this list — showing them turns the model's job into picking a
 * token it has already been given, and turns the attorney's into circling one.
 */
export function worksheetLine(field: string): string {
  const meta = getDesignSheetImportFieldMeta(field)
  if (!meta) throw new Error(`Unknown design-sheet field in the meeting spec: ${field}`)

  if (meta.options) return `${meta.label}: ${meta.options.join('  /  ')}`
  if (meta.kind === 'boolean') return `${meta.label}: yes  /  no`
  if (meta.kind === 'number') return `${meta.label}: __________`
  return `${meta.label}: ${ANSWER_RULE}`
}

function promptLine(prompt: string): string {
  return `${prompt}: ${ANSWER_RULE}`
}

function sectionLines(section: DesignMeetingSection): string[] {
  return [
    ...section.fields.map(worksheetLine),
    ...(section.prompts ?? []).map(promptLine),
  ]
}

// --- worksheet ---------------------------------------------------------------

function paragraph(text: string, options: { bold?: boolean; italics?: boolean; spacingAfter?: number } = {}) {
  return new Paragraph({
    spacing: { after: options.spacingAfter ?? 160 },
    children: [new TextRun({ text, bold: options.bold, italics: options.italics })],
  })
}

function buildWorksheetDocument(): Document {
  const children: Paragraph[] = [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 80 },
      children: [new TextRun({ text: 'Estate Plan Design Meeting Worksheet', bold: true, size: 32 })],
    }),
    paragraph('Client: ______________________________     Matter: ______________________________     Date: ______________', { spacingAfter: 240 }),
    paragraph(
      'Write answers after each colon and leave the labels as printed — the labels are what the '
      + 'design sheet reads when this is uploaded. For a line offering choices, circle one. '
      + 'Leave anything undecided blank rather than guessing; a blank stays an open question, a '
      + 'guess becomes a drafted document.',
      { italics: true, spacingAfter: 320 },
    ),
  ]

  for (const section of DESIGN_MEETING_SECTIONS) {
    children.push(new Paragraph({
      heading: HeadingLevel.HEADING_2,
      spacing: { before: 240, after: 60 },
      children: [new TextRun({ text: section.title, bold: true })],
    }))
    children.push(paragraph(section.intro, { italics: true, spacingAfter: 140 }))
    // One paragraph per line, never a table: mammoth's raw-text extraction (the
    // upload path) breaks only after paragraphs, so a two-column table row comes
    // out as label and value separated by a blank line with nothing pairing them.
    for (const line of sectionLines(section)) children.push(paragraph(line))
  }

  return new Document({
    creator: 'Aubrey Law',
    lastModifiedBy: 'Aubrey Law',
    revision: 1,
    sections: [{ properties: {}, children }],
  })
}

/**
 * Strip every source of run-to-run variance from the DOCX so the checked-in file
 * is byte-stable. Same approach as the other template generators in this repo.
 */
function normalizeDocx(buffer: Buffer): Buffer {
  const inputZip = new PizZip(buffer)
  const outputZip = new PizZip()

  for (const name of Object.keys(inputZip.files).sort()) {
    const file = inputZip.files[name]

    if (file.dir) {
      outputZip.file(name, '', { dir: true, date: deterministicZipEntryDate })
      continue
    }

    const content = name === 'docProps/core.xml'
      ? file.asText()
        .replace(
          /<dcterms:created xsi:type="dcterms:W3CDTF">.*?<\/dcterms:created>/,
          `<dcterms:created xsi:type="dcterms:W3CDTF">${deterministicCoreDocxTimestamp}</dcterms:created>`,
        )
        .replace(
          /<dcterms:modified xsi:type="dcterms:W3CDTF">.*?<\/dcterms:modified>/,
          `<dcterms:modified xsi:type="dcterms:W3CDTF">${deterministicCoreDocxTimestamp}</dcterms:modified>`,
        )
      : file.asNodeBuffer()

    outputZip.file(name, content, { date: deterministicZipEntryDate, binary: Buffer.isBuffer(content) })
  }

  return outputZip.generate({ type: 'nodebuffer', compression: 'DEFLATE', platform: 'DOS' })
}

// --- checklist ---------------------------------------------------------------

function buildChecklist(): string {
  const lines: string[] = [
    '# Estate Plan Design Meeting — Checklist',
    '',
    GENERATED_NOTE,
    '',
    'The order to work through a design meeting, and what each section has to come away with.',
    'Pair it with `design-meeting-worksheet.docx`, which carries the same sections in the same',
    'order and is what gets uploaded afterwards.',
    '',
    '## Before the meeting',
    '',
    '- [ ] Open the matter at `/admin/drafting/<matterId>` so the design sheet is seeded.',
    '- [ ] Note the number on the **Complete sheet** button — that is what still blocks drafting.',
    '- [ ] Run **Complete sheet → Fill what is missing** and accept what intake already supports,',
    '      so the meeting is spent on decisions rather than on data entry.',
    '- [ ] Print the worksheet, or open it alongside the sheet.',
    '',
    '## During the meeting',
    '',
  ]

  for (const [index, section] of DESIGN_MEETING_SECTIONS.entries()) {
    lines.push(`### ${index + 1}. ${section.title}`, '', section.intro, '')
    for (const field of section.fields) {
      const meta = getDesignSheetImportFieldMeta(field)
      if (!meta) throw new Error(`Unknown design-sheet field in the meeting spec: ${field}`)
      const options = meta.options ? ` — ${meta.options.join(' / ')}` : ''
      lines.push(`- [ ] ${meta.label}${options}`)
    }
    for (const prompt of section.prompts ?? []) lines.push(`- [ ] ${prompt}`)
    lines.push('')
  }

  lines.push(
    '## After the meeting',
    '',
    '- [ ] Upload the worksheet: **Complete sheet → Word document → Read document**.',
    '- [ ] Review the proposed rows. Anything in the **rejected** panel is a value the field',
    '      cannot hold — set it on the sheet directly rather than rewording the worksheet.',
    '- [ ] Check the **People** group before accepting: a row badged *Creates a new contact*',
    '      will mint a contact record, so confirm it is not someone already on the matter under',
    '      a different spelling.',
    '- [ ] Accept, then confirm the **Complete sheet** count dropped.',
    '- [ ] Anything left undecided stays a client question — it belongs in Concerns, not in a',
    '      value nobody chose.',
    '',
  )

  return lines.join('\n')
}

// --- granola template --------------------------------------------------------

function buildGranolaTemplate(): string {
  const lines: string[] = [
    '# Granola Template — Estate Plan Design Meeting',
    '',
    GENERATED_NOTE,
    '',
    'Paste the sections below into Granola\'s template editor. They mirror the worksheet, so a',
    'note taken against this template already carries the labels the design sheet reads.',
    '',
    'Two ways the note reaches the sheet:',
    '',
    '1. Paste it into **Complete sheet → Paste notes**.',
    '2. Attach it to the matter with **Add meeting notes**; **Fill what is missing** reads recent',
    '   matter notes on its own.',
    '',
    '---',
    '',
    '## Template',
    '',
    '**Instructions for the notetaker**',
    '',
    'Capture only what was actually said. Where a decision was not reached, write',
    '"not decided" rather than inferring one — an unanswered question is a useful output, and a',
    'plausible guess becomes a drafted document. Use the client\'s own words for names.',
    '',
  ]

  for (const section of DESIGN_MEETING_SECTIONS) {
    lines.push(`### ${section.title}`, '', section.intro, '')
    for (const field of section.fields) {
      const meta = getDesignSheetImportFieldMeta(field)
      if (!meta) throw new Error(`Unknown design-sheet field in the meeting spec: ${field}`)
      const options = meta.options ? ` (${meta.options.join(' / ')})` : ''
      lines.push(`- ${meta.label}${options}:`)
    }
    for (const prompt of section.prompts ?? []) lines.push(`- ${prompt}:`)
    lines.push('')
  }

  return lines.join('\n')
}

// --- entry points ------------------------------------------------------------

export interface DesignMeetingArtifacts {
  worksheet: Buffer
  markdown: Record<string, string>
}

export async function buildDesignMeetingArtifacts(): Promise<DesignMeetingArtifacts> {
  return {
    worksheet: normalizeDocx(await Packer.toBuffer(buildWorksheetDocument())),
    markdown: {
      [CHECKLIST_PATH]: buildChecklist(),
      [GRANOLA_PATH]: buildGranolaTemplate(),
    },
  }
}

async function main() {
  const repoRoot = process.cwd()
  const { worksheet, markdown } = await buildDesignMeetingArtifacts()

  const worksheetOut = path.join(repoRoot, WORKSHEET_PATH)
  fs.mkdirSync(path.dirname(worksheetOut), { recursive: true })
  fs.writeFileSync(worksheetOut, worksheet)
  console.log(`Wrote ${WORKSHEET_PATH}`)

  for (const [relative, content] of Object.entries(markdown)) {
    const out = path.join(repoRoot, relative)
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, content)
    console.log(`Wrote ${relative}`)
  }
}

if (process.argv[1] && process.argv[1].includes('generate-design-meeting-forms')) {
  void main()
}
