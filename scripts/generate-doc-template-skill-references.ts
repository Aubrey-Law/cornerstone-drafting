export function buildSkillReferenceFiles(repoRoot = process.cwd()): Record<string, string> {
  const generatorRoot = resolveNodeEstateGeneratorRoot()
  const dictionary = readJson<Record<string, DictionaryEntry>>(
    path.join(generatorRoot, 'schemas', 'data-dictionary.json'),
  )
  const catalog = buildTemplateVariableCatalog(generatorRoot)
  const packagesDir = path.join(generatorRoot, 'packages')
  const packageNames = fs.readdirSync(packagesDir)
    .filter(file => file.endsWith('.json'))
    .map(file => file.replace(/\.json$/, ''))
    .sort()

  crossCheckSelectionRules(repoRoot, packageNames)

  return {
    'fields.md': buildFieldsMd(dictionary, catalog),
    'context-flags.md': buildContextFlagsMd(dictionary),
    'packages.md': buildPackagesMd(packagesDir, packageNames),
    'clauses.md': buildClausesMd(generatorRoot),
    'missing-field-design-map.md': buildMissingFieldMapMd(dictionary),
  }
}

function buildFieldsMd(
  dictionary: Record<string, DictionaryEntry>,
  catalog: ReturnType<typeof buildTemplateVariableCatalog>,
): string {
  let out = GENERATED_NOTE('schemas/data-dictionary.json and the template variable catalog')
  out += '# Canonical merge fields\n\n'
  out += 'Every `{{ path }}` in a template must resolve to one of these paths (or a derived context flag — see context-flags.md). `[]` marks array item fields (`children[].full_name` is reached inside `{% for child in children %}` as `child.full_name`).\n\n'
  out += '| Field path | Type | Required | Description |\n|---|---|---|---|\n'
  for (const [field, entry] of Object.entries(dictionary).sort(([a], [b]) => a.localeCompare(b))) {
    out += `| \`${field}\` | ${entry.type} | ${entry.required === true ? 'yes' : entry.required === false ? 'no' : 'conditional'} | ${mdEscape(entry.description)} |\n`
  }
  out += '\n# Variables used per template\n\n'
  out += 'From `schemas/template-variables.generated.json` (regenerate with `npx tsx scripts/extract-template-variables.ts`). Loop-local variables are excluded.\n\n'
  for (const entry of [...catalog].sort((a, b) => a.template.localeCompare(b.template))) {
    out += `## ${entry.template}\n\n`
    if (entry.variables.length > 0) out += `Variables: ${entry.variables.map(v => `\`${v}\``).join(', ')}\n\n`
    if (entry.clauses.length > 0) out += `Clauses: ${entry.clauses.map(c => `\`${c}\``).join(', ')}\n\n`
    if (entry.variables.length === 0 && entry.clauses.length === 0) out += 'No merge fields (static document).\n\n'
  }
  return out
}

function buildContextFlagsMd(dictionary: Record<string, DictionaryEntry>): string {
  // Build the context from an empty payload: every derived flag and defaulted
  // sub-object appears with its default value.
  const context = buildNodeEstateContext({ data: {} as NodeEstateData, state: 'MA' })
  const dictionaryRoots = new Set(Object.keys(dictionary).map(field => field.split(/[.[]/)[0]))

  const flags: Array<[string, unknown]> = []
  const dataRoots: string[] = []
  for (const [key, value] of Object.entries(context as unknown as Record<string, unknown>).sort(([a], [b]) => a.localeCompare(b))) {
    if (dictionaryRoots.has(key)) dataRoots.push(key)
    else flags.push([key, value])
  }

  let out = GENERATED_NOTE('buildNodeEstateContext() in lib/estateGenerator/node/context.ts')
  out += '# Derived context flags\n\n'
  out += 'These names are available in templates *in addition to* the data-dictionary fields. They are computed by `buildNodeEstateContext()` from the payload — never ask the design sheet to populate them directly. Default value shown is what an empty payload produces.\n\n'
  out += '| Name | Empty-payload default | Notes |\n|---|---|---|\n'
  for (const [key, value] of flags) {
    const rendered = typeof value === 'object' ? JSON.stringify(value) : String(value)
    const display = rendered.length > 60 ? `${rendered.slice(0, 57)}…` : rendered
    out += `| \`${key}\` | \`${mdEscape(display)}\` | ${FLAG_ANNOTATIONS[key] ?? ''} |\n`
  }
  out += '\n## Data roots also present in the context\n\n'
  out += `${dataRoots.map(root => `\`${root}\``).join(', ')} — see fields.md for their fields. `
  out += 'Note the context defaults several nested values (e.g. `will.pr_structure` → `single`, `will.bond` → `no_bond`, `will.utma_age` → `21`), and aliases display fields:\n\n'
  const execution = (context as unknown as Record<string, Record<string, unknown>>).execution ?? {}
  out += '| Execution field | Empty-payload default |\n|---|---|\n'
  for (const [key, value] of Object.entries(execution).sort(([a], [b]) => a.localeCompare(b))) {
    out += `| \`execution.${key}\` | \`${mdEscape(String(value))}\` | \n`
  }
  for (const [key, note] of Object.entries(FLAG_ANNOTATIONS)) {
    if (key.includes('.')) out += `\n- \`${key}\`: ${note}`
  }
  out += '\n'
  return out
}

interface PackageManifest {
  name: string
  description: string
  required_fields: string[]
  documents: Array<{ id: string, title: string, template: string, output: string }>
}

function buildPackagesMd(packagesDir: string, packageNames: string[]): string {
  let out = GENERATED_NOTE('tools/aubreylaw-docgeneration/packages/*.json and deriveEstateGeneratorPackages()')
  out += '# Package manifests\n\n'
  for (const name of packageNames) {
    const manifest = readJson<PackageManifest>(path.join(packagesDir, `${name}.json`))
    out += `## ${name}\n\n${manifest.description}\n\n`
    out += '| Document | Template | Output |\n|---|---|---|\n'
    for (const document of manifest.documents) {
      out += `| ${mdEscape(document.title)} | \`${document.template}\` | \`${document.output}\` |\n`
    }
    out += `\nRequired fields: ${manifest.required_fields.length > 0 ? manifest.required_fields.map(field => `\`${field}\``).join(', ') : '(none)'}\n\n`
  }
  out += '# Design-sheet selection rules\n\n'
  out += 'How `deriveEstateGeneratorPackages()` (lib/estateGenerator/toGeneratorData.ts) turns `payload.documents.include_*` inclusions into packages. Inclusions come from the design sheet\'s `decisions.document_inclusions` (lib/designSheetDocumentInclusions.ts).\n\n'
  out += '| Inclusion key | Package(s) | Condition |\n|---|---|---|\n'
  for (const rule of SELECTION_RULES) {
    out += `| \`${rule.inclusionKey}\` | ${rule.packages.map(pkg => `\`${pkg}\``).join(', ')} | ${rule.condition} |\n`
  }
  out += `\nManifests never selected by \`deriveEstateGeneratorPackages()\`: ${[...UNREACHABLE_PACKAGES].sort().map(pkg => `\`${pkg}\``).join(', ')} (\`design-summary\` is generated from its own design-sheet action; \`core-estate\` is legacy and not in \`NODE_SUPPORTED_PACKAGES\`).\n`
  return out
}

interface ClauseJson {
  id: string
  title?: string
  document_type?: string
  jurisdiction?: string
  condition?: string | null
  required_fields?: string[]
  review_status?: string
  version_date?: string
  text?: string
}

function buildClausesMd(generatorRoot: string): string {
  const clauseFiles: Array<{ file: string, clause: ClauseJson }> = []
  const baseDir = path.join(generatorRoot, 'clauses')
  for (const file of fs.readdirSync(baseDir).filter(name => name.endsWith('.json')).sort()) {
    clauseFiles.push({ file: `clauses/${file}`, clause: readJson<ClauseJson>(path.join(baseDir, file)) })
  }
  const statesDir = path.join(generatorRoot, 'states')
  for (const state of fs.readdirSync(statesDir).sort()) {
    const stateClauseDir = path.join(statesDir, state, 'clauses')
    if (!fs.existsSync(stateClauseDir)) continue
    for (const file of fs.readdirSync(stateClauseDir).filter(name => name.endsWith('.json')).sort()) {
      clauseFiles.push({ file: `states/${state}/clauses/${file}`, clause: readJson<ClauseJson>(path.join(stateClauseDir, file)) })
    }
  }

  let out = GENERATED_NOTE('tools/aubreylaw-docgeneration/clauses/*.json and states/*/clauses/*.json')
  out += '# Clause inventory\n\n'
  out += 'Templates pull these with `{{ include_clause("id") }}` (state overrides win over `base` for the same id). A clause with a `condition` is dropped when that context flag is falsy; attorney force-include/omit overrides in the app require the clause to have a condition.\n\n'
  for (const { file, clause } of clauseFiles) {
    out += `## \`${clause.id}\`\n\n`
    out += `- Source: \`${file}\`\n`
    if (clause.title) out += `- Title: ${clause.title}\n`
    if (clause.document_type) out += `- Document type: ${clause.document_type}\n`
    out += `- Jurisdiction: ${clause.jurisdiction ?? 'base'}\n`
    out += `- Condition: ${clause.condition ? `\`${clause.condition}\`` : '(always included)'}\n`
    if (clause.required_fields?.length) out += `- Required fields: ${clause.required_fields.map(field => `\`${field}\``).join(', ')}\n`
    out += `- Review status: ${clause.review_status ?? 'unknown'}${clause.version_date ? ` (${clause.version_date})` : ''}\n`
    if (clause.text) out += `\n\`\`\`\n${clause.text}\n\`\`\`\n`
    out += '\n'
  }
  return out
}

function buildMissingFieldMapMd(dictionary: Record<string, DictionaryEntry>): string {
  let out = GENERATED_NOTE('designTargetForMissingField() in lib/estateGenerator/missingFieldDesignMap.ts')
  out += '# Field → design-sheet location\n\n'
  out += 'Where the drafting UI sends the attorney when a generator field is missing. When adding a field a template needs, add an exact entry in `lib/estateGenerator/missingFieldDesignMap.ts` (prefix fallbacks only scroll to a section).\n\n'
  out += '| Field path | Label | Design-sheet section | Target column |\n|---|---|---|---|\n'
  for (const field of Object.keys(dictionary).sort((a, b) => a.localeCompare(b))) {
    const target = designTargetForMissingField(field)
    out += `| \`${field}\` | ${mdEscape(target.label)} | ${mdEscape(target.sectionLabel)} | ${target.targetField ? `\`${target.targetField}\`` : '(section)'} |\n`
  }
  return out
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

const isMain = process.argv[1]
  && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (isMain) {
  const repoRoot = process.cwd()
  const outDir = path.join(repoRoot, SKILL_GENERATED_DIR)
  fs.mkdirSync(outDir, { recursive: true })
  const files = buildSkillReferenceFiles(repoRoot)
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(outDir, name), content)
    console.log(`Wrote ${path.join(SKILL_GENERATED_DIR, name)}`)
  }
  console.log('✓ skill references regenerated')
}
