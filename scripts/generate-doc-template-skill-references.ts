/**
 * Regenerate the doc-template skill's reference files:
 *   npm run skill:refs
 *
 * Derives the Markdown references bundled with the
 * `.claude/skills/aubreylaw-doc-templates` skill directly from the generator's
 * own sources (data dictionary, template variable catalog, merge context,
 * package manifests, clause JSON, missing-field design map) so the skill can
 * never drift from the code. CI checks freshness via
 * tests/skill-references-freshness.test.ts. Deterministic output — no
 * timestamps, sorted iteration.
 */
