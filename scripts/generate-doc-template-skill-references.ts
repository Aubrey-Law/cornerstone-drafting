// Packages that exist as manifests but are never emitted by
// deriveEstateGeneratorPackages(). Keep in sync deliberately.
const UNREACHABLE_PACKAGES = new Set(['core-estate', 'design-summary'])

function crossCheckSelectionRules(repoRoot: string, packageNames: string[]): void {
  const source = fs.readFileSync(path.join(repoRoot, 'lib/estateGenerator/toGeneratorData.ts'), 'utf8')
  const fnStart = source.indexOf('export function deriveEstateGeneratorPackages')
  const fnEnd = source.indexOf('\n}', fnStart)
  const fnSource = source.slice(fnStart, fnEnd)

  const sourceKeys = new Set(Array.from(fnSource.matchAll(/docs\.(include_\w+|spouse_docs|trust_planning_type)/g), m => m[1]))
  const sourcePackages = new Set(Array.from(fnSource.matchAll(/'([a-z0-9-]+)'/g), m => m[1])
    .filter(token => packageNames.includes(token)))

  const tableKeys = new Set(SELECTION_RULES.map(rule => rule.inclusionKey))
  const tablePackages = new Set(SELECTION_RULES.flatMap(rule => rule.packages))

  const problems: string[] = []
  for (const key of sourceKeys) {
    if (key.startsWith('include_') && !tableKeys.has(key)) problems.push(`inclusion key ${key} used by deriveEstateGeneratorPackages() but missing from SELECTION_RULES`)
  }
  for (const key of tableKeys) {
    if (!sourceKeys.has(key)) problems.push(`SELECTION_RULES lists ${key}, which deriveEstateGeneratorPackages() no longer reads`)
  }
  for (const pkg of sourcePackages) {
    if (!tablePackages.has(pkg)) problems.push(`package ${pkg} emitted by deriveEstateGeneratorPackages() but missing from SELECTION_RULES`)
  }
  for (const pkg of tablePackages) {
    if (!sourcePackages.has(pkg)) problems.push(`SELECTION_RULES lists package ${pkg}, which deriveEstateGeneratorPackages() never emits`)
    if (!packageNames.includes(pkg)) problems.push(`SELECTION_RULES lists package ${pkg}, which has no manifest`)
  }
  for (const pkg of packageNames) {
    if (!tablePackages.has(pkg) && !UNREACHABLE_PACKAGES.has(pkg)) {
      problems.push(`package ${pkg} has a manifest but is neither in SELECTION_RULES nor listed as unreachable`)
    }
  }
  if (problems.length > 0) {
    throw new Error(`Package selection table is out of sync with the code:\n  ${problems.join('\n  ')}`)
  }
}

