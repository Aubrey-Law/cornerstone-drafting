const GENERATED_NOTE = (source: string) =>
  `<!-- Generated by scripts/generate-doc-template-skill-references.ts from ${source} — do not edit; run \`npm run skill:refs\`. -->\n\n`

export const SKILL_GENERATED_DIR = '.claude/skills/aubreylaw-doc-templates/references/generated'

interface DictionaryEntry {
  type: string
  required: boolean | 'conditional'
  description: string
}

function readJson<T>(filePath: string): T {
  return JSON.parse(fs.readFileSync(filePath, 'utf8')) as T
}

function mdEscape(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

