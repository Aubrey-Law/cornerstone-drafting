CREATE TABLE IF NOT EXISTS public.document_template_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  template_id text NOT NULL,
  version_number bigint GENERATED BY DEFAULT AS IDENTITY,
  storage_path text NOT NULL UNIQUE,
  original_filename text NOT NULL,
  byte_size bigint NOT NULL CHECK (byte_size > 0 AND byte_size <= 15728640),
  sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  validation_status text NOT NULL DEFAULT 'pending'
    CHECK (validation_status IN ('pending', 'valid', 'invalid')),
  validation_report jsonb,
  validated_with_matter_id uuid REFERENCES public.matters(id) ON DELETE SET NULL,
  uploaded_by uuid NOT NULL REFERENCES public.users(id),
  validated_by uuid REFERENCES public.users(id),
  validated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (template_id, sha256)
);

CREATE INDEX IF NOT EXISTS document_template_versions_template_idx
  ON public.document_template_versions (template_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.document_template_publications (
  template_id text PRIMARY KEY,
  version_id uuid NOT NULL REFERENCES public.document_template_versions(id),
  published_by uuid NOT NULL REFERENCES public.users(id),
  published_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.document_template_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id text NOT NULL,
  version_id uuid REFERENCES public.document_template_versions(id),
  previous_version_id uuid REFERENCES public.document_template_versions(id),
  event_type text NOT NULL CHECK (event_type IN ('uploaded', 'validated', 'validation_failed', 'published', 'rolled_back')),
  actor_id uuid NOT NULL REFERENCES public.users(id),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS document_template_events_template_idx
  ON public.document_template_events (template_id, created_at DESC);

