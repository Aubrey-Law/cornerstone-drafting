-- Unify leads and hired matters around a matter-owned opportunity.
-- Drafting remains hired-only; client_intake remains the intake/person record.

alter table public.matters
  add column if not exists relationship_status text not null default 'hired',
  add column if not exists hired_at timestamptz,
  add column if not exists lost_at timestamptz,
  add column if not exists lost_reason text;

alter table public.matters
  drop constraint if exists matters_relationship_status_check,
  add constraint matters_relationship_status_check
    check (relationship_status in ('lead', 'hired', 'lost'));

create index if not exists matters_relationship_status_idx
  on public.matters (relationship_status, status, created_at desc);

-- Existing matters are represented work. Standalone lead intakes receive an
-- unnumbered opportunity without client access or drafting initialization.
update public.matters
set relationship_status = 'hired',
    hired_at = coalesce(hired_at, created_at)
where relationship_status = 'hired';

insert into public.matters (
  client_intake_id, client_id, name, matter_number, stage, status,
  stage_entered_at, track, relationship_status, hired_at, lost_at
)
select
  ci.id,
  null,
  coalesce(nullif(trim(ci.full_name), ''), nullif(trim(concat_ws(' ', ci.first_name, ci.last_name)), ''), ci.email, 'Prospective client'),
  null,
  case
    when ci.engagement_sent_at is not null then 'engagement_sent'
    when ci.intake_completed_at is not null then 'intake_completed'
    when ci.intake_sent_at is not null then 'intake_sent'
    else 'new_lead'
  end,
  'active',
  coalesce(ci.engagement_sent_at, ci.intake_completed_at, ci.intake_sent_at, ci.created_at, now()),
  'DEFAULT',
  case when ci.lead_status = 'lost' then 'lost' else 'lead' end,
  null,
  case when ci.lead_status = 'lost' then coalesce(ci.updated_at, now()) else null end
from public.client_intake ci
where ci.lead_status is not null
  and not exists (
    select 1 from public.matters existing where existing.client_intake_id = ci.id
  );

update public.client_intake ci
set matter_id = (
  select m.id
  from public.matters m
  where m.client_intake_id = ci.id
  order by (m.relationship_status = 'hired') desc, m.created_at desc
  limit 1
)
where ci.lead_status is not null
  and exists (select 1 from public.matters m where m.client_intake_id = ci.id)
  and ci.matter_id is distinct from (
    select m.id
    from public.matters m
    where m.client_intake_id = ci.id
    order by (m.relationship_status = 'hired') desc, m.created_at desc
    limit 1
  );

insert into public.matter_details (
  client_id, practice_area, plan_type, jurisdiction_state, jurisdiction_county,
  flat_fee_amount, est_estate_value, referral_source, urgency, matter_status_notes
)
select
  m.id,
  ci.practice_area,
  'TBD',
  coalesce(nullif(ci.state, ''), 'MA'),
  nullif(ci.county, ''),
  ci.engagement_fee_quoted,
  ci.taxable_estate,
  nullif(ci.lead_source, ''),
  ci.lead_urgency,
  nullif(ci.qualification_notes, '')
from public.matters m
join public.client_intake ci on ci.id = m.client_intake_id
where m.relationship_status in ('lead', 'lost')
on conflict (client_id) do update set
  practice_area = excluded.practice_area,
  jurisdiction_state = excluded.jurisdiction_state,
  jurisdiction_county = excluded.jurisdiction_county,
  flat_fee_amount = excluded.flat_fee_amount,
  est_estate_value = excluded.est_estate_value,
  referral_source = excluded.referral_source,
  urgency = excluded.urgency,
  matter_status_notes = excluded.matter_status_notes,
  updated_at = now();

