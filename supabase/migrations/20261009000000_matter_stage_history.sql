-- Stage is the field the practice is managed by, and it had no record.
--
-- `matters.relationship_status` has kept an insert-only history since
-- 20260802000000, so "when did this become a client, and who marked it" is
-- answerable. `matters.stage` — the field the aging board, the SLA clock, the
-- task engine and the drafting queue all key off — kept only its current value
-- and `stage_entered_at`. The moment a matter moved on, the previous stage and
-- the date it was entered were gone. Nothing could answer how long a matter
-- actually sat in Drafting, whether it had been walked backwards, or who moved
-- it.
--
-- This is the same shape as the relationship history: insert-only, staff-read,
-- written by a trigger on the column itself so no caller can forget it.
--
-- Two deliberate differences from that precedent:
--
--  1. **No CHECK constraint on the stage columns.** The relationship history's
--     CHECK is exactly the cautionary tale — it was written with three states,
--     lifecycle v3 added `declined`, and the constraint was left behind until
--     20260824000000 caught it. Stage has a far larger vocabulary that has
--     already moved more than once (`discovery_call` added in 20260910000000,
--     `design_input` split in 20260903000001, `revision` reordered in
--     20260913000000). A history table records what happened; pinning it to
--     today's vocabulary means the next stage change either breaks the audit
--     insert or silently blocks a legitimate transition. `matters.stage` is
--     constrained at the source (20261007000000), which is where it belongs.
--
--  2. **`entered_at` is separate from `created_at`.** Since 20260910000000 a
--     caller can pin `stage_entered_at` deliberately — the discovery-call
--     anchor sets it to the date of the call, not the date of the write. So the
--     business date a stage was entered and the moment the row was recorded are
--     genuinely different facts, and a duration computed from the wrong one
--     would be wrong. Both are kept.

create table if not exists public.matter_stage_history (
  id bigint generated by default as identity primary key,
  matter_id uuid not null references public.matters(id) on delete cascade,
  from_stage text,
  to_stage text not null,
  -- The business date the matter entered `to_stage` (mirrors stage_entered_at).
  entered_at timestamptz not null default now(),
  actor_id uuid references auth.users(id) on delete set null,
  -- The moment this row was written, which can differ from `entered_at`.
  created_at timestamptz not null default now()
);

-- Ordered by the business date, which is how a stage timeline reads.
create index if not exists matter_stage_history_matter_idx
  on public.matter_stage_history (matter_id, entered_at desc);

alter table public.matter_stage_history enable row level security;

drop policy if exists "Staff read matter stage history" on public.matter_stage_history;

create policy "Staff read matter stage history"
  on public.matter_stage_history for select to authenticated
  using (exists (
    select 1 from public.users u
    where u.id = (select auth.uid()) and u.role in ('attorney', 'admin', 'va', 'staff')
  ));

grant select on public.matter_stage_history to authenticated;
grant select, insert on public.matter_stage_history to service_role;
grant usage, select on sequence public.matter_stage_history_id_seq to service_role;

-- ── Recording ───────────────────────────────────────────────────────────────
-- Actor resolution matches `record_matter_relationship_status_change()`: the
-- app sets `app.actor_id` for service-role writes, and `auth.uid()` covers the
-- RLS path. Neither is guaranteed, so actor_id stays nullable — an unattributed
-- transition is still worth recording.

create or replace function public.record_matter_stage_change()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
declare
  v_actor_id uuid;
begin
  if tg_op = 'UPDATE' and new.stage is not distinct from old.stage then
    return new;
  end if;
  if new.stage is null then
    return new;
  end if;

  begin
    v_actor_id := nullif(current_setting('app.actor_id', true), '')::uuid;
  exception when invalid_text_representation then
    v_actor_id := null;
  end;
  v_actor_id := coalesce(v_actor_id, auth.uid());

  insert into public.matter_stage_history (matter_id, from_stage, to_stage, entered_at, actor_id)
  values (
    new.id,
    case when tg_op = 'UPDATE' then old.stage else null end,
    new.stage,
    coalesce(new.stage_entered_at, now()),
    v_actor_id
  );
  return new;
end;
$$;

revoke execute on function public.record_matter_stage_change() from public, anon, authenticated;

-- AFTER, so `trg_matters_stage_entered_at` (BEFORE UPDATE OF stage) has already
-- settled `stage_entered_at` and the recorded date is the one that persists.
drop trigger if exists record_matter_stage_change on public.matters;
create trigger record_matter_stage_change
after insert or update of stage on public.matters
for each row execute function public.record_matter_stage_change();

-- ── Backfill ────────────────────────────────────────────────────────────────
-- One row per existing matter for the stage it is on now. Earlier transitions
-- were never recorded and cannot be recovered, so this seeds the timeline from
-- today rather than inventing history: `from_stage` is null and `entered_at` is
-- the matter's own `stage_entered_at`. Idempotent by matter.

insert into public.matter_stage_history (matter_id, from_stage, to_stage, entered_at)
select m.id, null, m.stage, coalesce(m.stage_entered_at, m.created_at, now())
from public.matters m
where m.stage is not null
  and not exists (
    select 1 from public.matter_stage_history h where h.matter_id = m.id
  );

comment on table public.matter_stage_history is
  'Insert-only record of every matters.stage transition, written by the '
  'record_matter_stage_change trigger. `entered_at` is the business date the '
  'stage was entered (stage_entered_at, which callers may pin); `created_at` is '
  'when the row was written. Rows with a null from_stage and the migration '
  'backfill date are seeded starting points, not observed transitions.';

notify pgrst, 'reload schema';
