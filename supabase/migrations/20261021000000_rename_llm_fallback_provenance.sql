-- Say which engine actually drafted a document.
--
-- matter_documents.generation_engine recorded 'python_fallback' for documents
-- produced by the per-document fallback path. That path calls /api/drafting —
-- an Anthropic completion — and the Python subprocess the label is named after
-- was retired long before; lib/estateGenerator/engine.ts documents that its
-- configured value now falls through to 'node'. So the provenance on a client's
-- will or trust named an engine that had not run in months.
--
-- Expand/contract, deliberately. This migration widens the constraint to accept
-- both labels and rewrites the existing rows. It does NOT drop 'python_fallback'
-- from the allowed set, because migrations apply on merge to main while the
-- code that stops writing the old label ships with the deploy: narrowing here
-- would make any draft generated in that window fail its insert. A follow-up
-- migration removes the old value once the deploy carrying llm_fallback has
-- been live and `select count(*) ... where generation_engine = 'python_fallback'`
-- is zero.

-- The original constraint was declared inline in the CREATE TABLE, so its name
-- was generated by Postgres. That is matter_documents_generation_engine_check
-- by the usual rule, but drop whatever check on this table actually mentions
-- the column rather than trusting the derivation.
do $$
declare
  v_name text;
begin
  for v_name in
    select con.conname
      from pg_constraint con
      join pg_class rel on rel.oid = con.conrelid
      join pg_namespace nsp on nsp.oid = rel.relnamespace
     where nsp.nspname = 'public'
       and rel.relname = 'matter_documents'
       and con.contype = 'c'
       and pg_get_constraintdef(con.oid) ilike '%generation_engine%'
  loop
    execute format('alter table public.matter_documents drop constraint %I', v_name);
  end loop;
end $$;

alter table public.matter_documents
  add constraint matter_documents_generation_engine_check
  check (
    generation_engine is null
    or generation_engine in ('node', 'supabase', 'llm_fallback', 'python_fallback')
  );

update public.matter_documents
   set generation_engine = 'llm_fallback'
 where generation_engine = 'python_fallback';
