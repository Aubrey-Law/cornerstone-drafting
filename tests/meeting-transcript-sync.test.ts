import fs from 'node:fs'
import { describe, expect, it, vi } from 'vitest'

/**
 * The meeting-transcripts sweep. A transcript lands on a record only when the
 * record is certain, is never read twice, and ends in the meeting follow-up.
 * These pin the matching table, the transcript reading, and the wiring.
 */

vi.mock('server-only', () => ({}))

import { attendeeEmailsFrom, matchMeetingToRecord, normalizeEmail } from '@/lib/meetings/transcriptMatch'
import { vttToTranscriptText } from '@/lib/meetings/transcriptText'
import { buildMeetingNoteMarkdown, slugifyMeetingTitle } from '@/lib/meetings/saveMatterMeetingNote'
import { SYSTEM_AUTOMATIONS } from '@/lib/automations/registry'

const MATTER = '00000000-0000-0000-0000-000000000060'
const MATTER_2 = '00000000-0000-0000-0000-000000000061'
const LEAD = '00000000-0000-0000-0000-000000000050'
const START = '2026-10-05T14:00:00.000Z'

const matters = [
  { id: MATTER, email: 'pat@example.com', name: 'Pat Client' },
  { id: MATTER_2, email: 'sam@example.com', name: 'Sam Client' },
]
const leads = [{ id: LEAD, email: 'lee@example.com', name: 'Lee Lead' }]
const staffEmails = ['scott@aubreylegal.com']
const base = { matters, leads, staffEmails, staffDomains: ['aubreylegal.com'], appointments: [] as never[], startIso: START }

describe('matching a meeting to a record', () => {
  it('reads emails out of "Name <email>" attendees and ignores the firm', () => {
    expect(attendeeEmailsFrom(['Pat Client <PAT@example.com>', 'scott@aubreylegal.com', 'not an email', 'lee@example.com']))
      .toEqual(['pat@example.com', 'scott@aubreylegal.com', 'lee@example.com'])
    expect(normalizeEmail(' Pat@Example.com ')).toBe('pat@example.com')
    expect(normalizeEmail('nope')).toBeNull()
    expect(matchMeetingToRecord({ ...base, attendeeEmails: ['scott@aubreylegal.com', 'paralegal@aubreylegal.com'] }))
      .toEqual({ kind: 'none', reason: 'no_attendees' })
  })

  it('prefers the appointment on the calendar at that time, linked to its record', () => {
    const appointments = [
      { id: 'a1', startIso: '2026-10-05T14:05:00.000Z', attendeeEmails: ['pat@example.com'], matterId: MATTER_2, leadId: null, label: 'Pat Client' },
    ]
    // The appointment's own link wins over the client email, which points at MATTER.
    expect(matchMeetingToRecord({ ...base, appointments, attendeeEmails: ['pat@example.com'] }))
      .toEqual({ kind: 'matter', id: MATTER_2, name: 'Pat Client', via: 'appointment' })
    // A day away is a different meeting.
    expect(matchMeetingToRecord({ ...base, appointments, attendeeEmails: ['pat@example.com'], startIso: '2026-10-07T14:00:00.000Z' }))
      .toEqual({ kind: 'matter', id: MATTER, name: 'Pat Client', via: 'email' })
    // An appointment linked to nothing is no evidence.
    const unlinked = [{ ...appointments[0], matterId: null }]
    expect(matchMeetingToRecord({ ...base, appointments: unlinked, attendeeEmails: ['pat@example.com'] }))
      .toEqual({ kind: 'matter', id: MATTER, name: 'Pat Client', via: 'email' })
  })

  it('falls back to exactly one matter, then exactly one lead, by email', () => {
    expect(matchMeetingToRecord({ ...base, attendeeEmails: ['lee@example.com'] }))
      .toEqual({ kind: 'lead', id: LEAD, name: 'Lee Lead', via: 'email' })
    expect(matchMeetingToRecord({ ...base, attendeeEmails: ['Pat@example.com', 'spouse@example.com'] }))
      .toEqual({ kind: 'matter', id: MATTER, name: 'Pat Client', via: 'email' })
  })

  it('refuses to guess between two records or when nobody matches', () => {
    expect(matchMeetingToRecord({ ...base, attendeeEmails: ['pat@example.com', 'sam@example.com'] }))
      .toEqual({ kind: 'none', reason: 'ambiguous' })
    const twoAppointments = [
      { id: 'a1', startIso: START, attendeeEmails: ['pat@example.com'], matterId: MATTER, leadId: null, label: null },
      { id: 'a2', startIso: START, attendeeEmails: ['sam@example.com'], matterId: MATTER_2, leadId: null, label: null },
    ]
    expect(matchMeetingToRecord({ ...base, appointments: twoAppointments, attendeeEmails: ['pat@example.com', 'sam@example.com'] }))
      .toEqual({ kind: 'none', reason: 'ambiguous' })
    expect(matchMeetingToRecord({ ...base, attendeeEmails: ['stranger@example.com'] }))
      .toEqual({ kind: 'none', reason: 'no_match' })
    // A matter and a lead sharing an email resolve to the matter: the hired record outranks the inquiry.
    expect(matchMeetingToRecord({ ...base, leads: [{ id: LEAD, email: 'pat@example.com', name: 'Pat' }], attendeeEmails: ['pat@example.com'] }))
      .toEqual({ kind: 'matter', id: MATTER, name: 'Pat Client', via: 'email' })
  })
})

describe('reading a Teams transcript', () => {
  it('turns WebVTT cues into speaker lines and joins a speaker’s consecutive cues', () => {
    const vtt = [
      'WEBVTT', '', 'NOTE generated by Teams', '',
      '1', '00:00:01.000 --> 00:00:04.000', '<v Pat Client>We want the house in the trust.</v>', '',
      '2', '00:00:04.500 --> 00:00:06.000', '<v Pat Client>And the lake place too.</v>', '',
      '00:00:07.000 --> 00:00:09.000', '<v Scott Aubrey>Both deeds, then &amp; a schedule A.</v>', '',
      '00:00:09.000 --> 00:00:10.000', 'An untagged line.',
    ].join('\n')
    expect(vttToTranscriptText(vtt)).toBe([
      'Pat Client: We want the house in the trust. And the lake place too.',
      'Scott Aubrey: Both deeds, then & a schedule A.',
      'An untagged line.',
    ].join('\n'))
    expect(vttToTranscriptText('WEBVTT\n\n')).toBe('')
  })
})

describe('saving a note on a matter', () => {
  it('writes the frontmatter the dialog always has, with the sweep’s source and link', () => {
    const markdown = buildMeetingNoteMarkdown({
      matterId: MATTER, title: 'Design meeting', meetingDate: '2026-10-05', content: 'Decided things.\n',
      source: 'microsoft_teams', sourceUrl: 'https://teams.microsoft.com/l/meetup-join/x', attendees: ['pat@example.com'],
    })
    expect(markdown).toContain('title: "Design meeting"')
    expect(markdown).toContain('source: "microsoft_teams"')
    expect(markdown).toContain('source_url: "https://teams.microsoft.com/l/meetup-join/x"')
    expect(markdown).toContain('attendees: "pat@example.com"')
    expect(markdown.trim().endsWith('Decided things.')).toBe(true)
    expect(slugifyMeetingTitle('Design meeting: Pat & Sam!')).toBe('design-meeting-pat-sam')
  })

  it('is the one writer for matter meeting notes, used by the dialog route and the sweep', () => {
    const lib = fs.readFileSync('lib/meetings/saveMatterMeetingNote.ts', 'utf8')
    expect(lib).toContain("source: 'meeting-notes'")
    expect(lib).toContain('meeting-notes/')
    expect(lib).toContain("from('matter_activity').insert")
    expect(lib).toContain("relationship_status !== 'hired'")
    const route = fs.readFileSync('app/api/admin/meeting-notes/route.ts', 'utf8')
    expect(route).toContain('saveMatterMeetingNote({')
    expect(route).not.toContain("from('matter_documents')")
    const sync = fs.readFileSync('lib/meetings/transcriptSync.ts', 'utf8')
    expect(sync).toContain('saveMatterMeetingNote({')
    expect(sync).not.toContain("from('matter_documents')")
  })
})

describe('the sweep', () => {
  const sync = fs.readFileSync('lib/meetings/transcriptSync.ts', 'utf8')

  it('is a system automation on the half hour, behind the shared run control', () => {
    const automation = SYSTEM_AUTOMATIONS.find(entry => entry.key === 'meeting-transcripts')
    expect(automation).toMatchObject({ path: '/api/cron/meeting-transcripts', schedules: ['*/30 * * * *'] })
    const route = fs.readFileSync('app/api/cron/meeting-transcripts/route.ts', 'utf8')
    expect(route).toContain("runSystemAutomation('meeting-transcripts'")
    expect(route).toContain('runMeetingTranscriptSync()')
    const migration = fs.readFileSync('supabase/migrations/20270107090000_meeting_transcript_imports.sql', 'utf8')
    expect(migration).toContain('create table public.meeting_transcript_imports')
    expect(migration).toContain('primary key (provider, external_id)')
    expect(migration).toContain("'system:meeting-transcripts'")
    expect(migration).toContain('revoke all on table public.meeting_transcript_imports from anon, authenticated')
  })

  it('acts as the firm’s unattended actor, records every transcript it looks at, and never reads one twice', () => {
    expect(sync).toContain('resolveUnattendedActor()')
    expect(sync).toContain("from('meeting_transcript_imports').upsert(")
    expect(sync).toContain("onConflict: 'provider,external_id'")
    expect(sync).toContain("context.imported.has(importKey('granola', note.id))")
    expect(sync).toContain("context.imported.has(importKey('microsoft_teams', meetingId))")
    // Unmatched and ambiguous meetings are written down too, so they are not asked about every half hour.
    expect(sync).toContain("skippedReason: match.reason")
    // A summary or transcript that is not ready yet is left for the next pass, not recorded.
    expect(sync).toContain("if (error instanceof GranolaError && error.status === 409) return 'pending'")
    expect(sync).toContain("if (!transcripts.length) return 'pending'")
    expect(sync).toContain('MAX_NOTES_PER_RUN = 5')
  })

  it('hands every saved note to the meeting follow-up, keyed to the note', () => {
    expect(sync).toContain('await runMeetingFollowUp({')
    expect(sync).toContain('sourceKey: noteId')
    // Granola on a lead goes through the idempotent import RPC; Teams through the manual one.
    expect(sync).toContain("rpc('import_lead_granola_note_with_activity'")
    expect(sync).toContain("rpc('create_lead_meeting_note_with_activity'")
  })

  it('reads Teams transcripts only with the transcript scope, and says so otherwise', () => {
    expect(sync).toContain('hasTranscriptScope(connection.scopes)')
    expect(sync).toContain("context.result.teams = 'reconnect_needed'")
    const teams = fs.readFileSync('lib/microsoftTeams.ts', 'utf8')
    expect(teams).toContain("REQUIRED_TRANSCRIPT_SCOPE = 'OnlineMeetingTranscript.Read.All'")
    expect(teams).toContain('REQUIRED_TEAMS_SCOPE, REQUIRED_TRANSCRIPT_SCOPE]')
    expect(teams).toContain('/transcripts/${encodeURIComponent(transcriptId)}/content?$format=text/vtt')
    const status = fs.readFileSync('app/api/admin/microsoft/status/route.ts', 'utf8')
    expect(status).toContain('hasTranscriptScope: hasTranscriptScope(conn?.scopes)')
  })
})
